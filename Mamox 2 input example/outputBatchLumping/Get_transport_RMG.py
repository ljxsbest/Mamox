import pandas as pd
from rmgpy.molecule import Molecule
from rmgpy.transport import TransportData

# 读取 CSV
species_df = pd.read_csv('speciesList_SMILES.csv')

# 存储输出行
output_lines = []

for index, row in species_df.iterrows():
    label = row['MECH_NAME']
    smiles = row['SMILES']
    
    # 构建分子对象
    try:
        molecule = Molecule().fromSMILES(smiles)
    except Exception as e:
        print(f"Error parsing SMILES {smiles}: {e}")
        continue
    
    # 估算输运参数
    try:
        transport_data = TransportData.fromMolecule(molecule)
    except Exception as e:
        print(f"Error estimating transport for {label}: {e}")
        continue
    
    # 获取分子量
    molecular_weight = molecule.getMolecularWeight()
    
    # Chemkin格式输出
    line = "{:<10} {:>8.2f} {:>6.3f} {:>7.1f} {:>5.1f} {:>5.2f} {:>5.1f}".format(
        label,
        molecular_weight,
        transport_data.sigma.value_si * 1e10,      # m -> Å
        transport_data.epsilon.value_si / 1.380649e-23,  # J -> K (kB)
        transport_data.dipoleMoment.value_si * 2.99792458e29, # C·m -> Debye
        transport_data.polarizability.value_si * 1e30,      # m^3 -> Å^3
        transport_data.rotrelaxcollnum
    )
    output_lines.append(line)

# 写入文件
with open('transport.dat', 'w') as f:
    f.write("! TRANSPORT PARAMETERS GENERATED BY RMG\n")
    for line in output_lines:
        f.write(line + "\n")

print("Transport data saved to transport.dat")
